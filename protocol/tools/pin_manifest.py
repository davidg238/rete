"""Fetch-and-pin the manifest at build time (#243 D5, design §5.1/§6).

Fetches the served manifest from porta (PORTA_MANIFEST_URL or --url), verifies
the endpoint's own hash claim, lints what it is about to pin, and writes:

  <out-dir>/MANIFEST.pinned.cddl     the pinned bytes
  <out-dir>/oevm_manifest_pin.txt    line 1: full sha256 hex; line 2: source=porta|repo
  [--emit-c <file>]                  a TU: oevm_manifest_pin[8] + len + source

Unreachable porta falls back to the repo's protocol/MANIFEST.cddl, LOUDLY and
stamped source=repo — the provision gate (check_provision.py) is what makes
the fallback safe. An endpoint that lies about its own hash is refused, not
trusted. A manifest that fails the lint is refused wherever it came from.
"""
import argparse
import hashlib
import sys
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path

from manifest_lint import lint

REPO_MANIFEST = Path(__file__).resolve().parents[1] / "MANIFEST.cddl"


class PinError(Exception):
    pass


@dataclass
class PinResult:
    source: str  # "porta" | "repo"
    sha256: str


def _fetch(url):
    with urllib.request.urlopen(url, timeout=10) as resp:
        body = resp.read()
        claimed = resp.headers.get("X-Manifest-SHA256", "")
    actual = hashlib.sha256(body).hexdigest()
    if claimed != actual:
        raise PinError(
            f"{url} claims sha256 {claimed[:12]}… but served {actual[:12]}… — refused")
    return body


def _emit_c(path, pin8, source):
    arr = ", ".join(f"0x{b:02x}" for b in pin8)
    path.write_text(
        "/* generated by protocol/tools/pin_manifest.py - do not edit, do not commit */\n"
        f"const unsigned char oevm_manifest_pin[8] = {{ {arr} }};\n"
        "const unsigned int oevm_manifest_pin_len = 8;\n"
        f'const char oevm_manifest_src[] = "{source}";\n')


def pin(out_dir, url, emit_c=None, repo_file=REPO_MANIFEST):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    body, source = None, None
    if url:
        try:
            body, source = _fetch(url), "porta"
        except PinError:
            raise
        except (urllib.error.URLError, OSError, TimeoutError) as e:
            print(f"pin_manifest: {url} unreachable ({e}); falling back to "
                  f"{repo_file} — provision will re-validate this pin (rete#243)",
                  file=sys.stderr)
    if body is None:
        body, source = Path(repo_file).read_bytes(), "repo"
    findings = lint(body.decode())
    if findings:
        raise PinError(f"manifest from {source} fails lint: " + "; ".join(findings))
    digest = hashlib.sha256(body).hexdigest()
    (out_dir / "MANIFEST.pinned.cddl").write_bytes(body)
    (out_dir / "oevm_manifest_pin.txt").write_text(f"{digest}\nsource={source}\n")
    if emit_c:
        _emit_c(Path(emit_c), bytes.fromhex(digest)[:8], source)
    return PinResult(source=source, sha256=digest)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--url", default=None,
                    help="porta's GET /manifest (default: $PORTA_MANIFEST_URL; unset = repo)")
    ap.add_argument("--emit-c", default=None)
    args = ap.parse_args()
    import os
    url = args.url or os.environ.get("PORTA_MANIFEST_URL")
    try:
        res = pin(out_dir=args.out_dir, url=url, emit_c=args.emit_c)
    except PinError as e:
        print(f"pin_manifest: {e}", file=sys.stderr)
        return 1
    print(f"pin_manifest: pinned {res.sha256[:12]}… (source={res.source})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
