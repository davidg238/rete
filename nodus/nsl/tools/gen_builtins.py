import re
import sys
from pathlib import Path

# Task 9a: repointed from the FROZEN oevm seed to the ACTIVE oevm builtins.def.
# The compiler's registry must follow the live VM as the registry compacts.
DEF = Path(__file__).resolve().parent.parent.parent / "oevm" / "src" / "builtins.def"
OUT = Path(__file__).resolve().parent / "builtins_registry.py"
VERSION = 6  # keep in lockstep with BUILTIN_REGISTRY_VERSION in oimg_loader.c


def parse():
    entries = []
    line_re = re.compile(r'BUILTIN\(\s*(\d+)\s*,\s*(\w+)\s*,\s*"([^"]*)"\s*\)')
    for line in DEF.read_text().splitlines():
        m = line_re.search(line)
        if m:
            entries.append((int(m.group(1)), m.group(2), m.group(3)))
    return entries


def main(out: Path = OUT):
    entries = parse()
    for i, (idx, _kind, _name) in enumerate(entries):
        if idx != i:
            sys.exit(f"builtins.def indices must be dense and ordered: row {i} has index {idx}")
    body = ",\n".join(f"    {name!r}: {idx}" for idx, _k, name in entries)
    text = f"# GENERATED by gen_builtins.py — do not edit.\nVERSION = {VERSION}\nREGISTRY = {{\n{body}\n}}\n"
    # rete#239: write ONLY when the content differs. A no-op regeneration that
    # touches mtime invalidates nothing visible but re-dates the file under the
    # importer's __pycache__ check — the exact seam where a stale .pyc once
    # served VERSION 6 out of a tree whose source said 5, and every image baked
    # that run was refused at load. Unchanged bytes -> unchanged mtime -> the
    # cached .pyc stays both valid and correct.
    if out.exists() and out.read_text() == text:
        print(f"unchanged {out} ({len(entries)} entries)")
        return
    out.write_text(text)
    print(f"wrote {out} ({len(entries)} entries)")


if __name__ == "__main__":
    # rete#239: an explicit output path keeps callers that must not touch the
    # tracked tree (the test generates into a tmpdir and compares) off the
    # default in-tree target.
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT)
